/**
 * Fonts a project brings with it (<project>.studio/fonts: those a CapCut project used), by the
 * family they're drawn with. Loaded from their files when the project opens.
 */
const projectFonts = new Map<string, FontDef>()
const faces = new Set<string>()

export async function useProjectFonts(list: { family: string; path: string }[]) {
  for (const f of list) {
    projectFonts.set(f.family, { family: f.family, use: 'This project’s', weights: [400], kind: 'sans' })
    if (faces.has(f.path)) continue
    try {
      const face = new FontFace(f.family, `url("studio-file://cache/${encodeURIComponent(f.path)}")`)
      await face.load()
      document.fonts.add(face)
      faces.add(f.path)
    } catch {}
  }
}
export const projectFontFamilies = () => [...projectFonts.keys()]

export const fontDef = (family: string) => FONTS.find((f) => f.family === family) ?? projectFonts.get(family) ?? FONTS[0]

/** A font's name in lists: "System" for Metropolis, else its family. */
export const fontLabel = (family: string) => FONTS.find((f) => f.family === family)?.label ?? family

/** The bundled weight closest to the one asked for. */
export function nearestWeight(family: string, weight: number) {
  return fontDef(family).weights.reduce((a, b) => (Math.abs(b - weight) < Math.abs(a - weight) ? b : a))
}

/** A CSS font string for canvas and previews. */
export function fontString(family: string, weight: number, size: number, italic = false) {
  return `${italic ? 'italic ' : ''}${nearestWeight(family, weight)} ${Math.max(1, Math.round(size))}px "${fontDef(family).family}", "IBM Plex Sans", sans-serif`
}

/** Waits until the font has loaded (canvas draws with a fallback otherwise). */
export async function loadFont(family: string, weight: number, italic = false, sample = 'AÅÄÖaåäö0') {
  try {
    await document.fonts.load(fontString(family, weight, 32, italic), sample)
  } catch {}
}
